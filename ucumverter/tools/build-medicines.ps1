<#
.SYNOPSIS
  Builds config/medicines.json, the offline fallback list of AMT medicines for UCUMverter.

.DESCRIPTION
  For each guideline in config/guidelines.json this script expands the guideline drugEcl
  on Ontoserver, then reads each product's strength with CodeSystem/$lookup.
  Rerun it whenever you change a guideline ECL.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\ucumverter\tools\build-medicines.ps1
#>
param(
  [string]$TxBase = 'https://tx.ontoserver.csiro.au/fhir',
  [string]$Edition = 'http://snomed.info/sct/32506021000036107'
)

$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$root = Split-Path -Parent $PSScriptRoot
$guidelinePath = Join-Path $root 'config\guidelines.json'
$outPath = Join-Path $root 'config\medicines.json'

$AMT = @{
  ConcValue  = '999000021000168100'
  ConcUnit   = '999000031000168102'
  TotalValue = '999000041000168106'
  TotalUnit  = '999000051000168108'
  Boss       = '732943007'
}
$headers = @{ Accept = 'application/fhir+json' }

function Get-PartValue($parts) {
  $v = $parts | Where-Object { $_.name -eq 'value' } | Select-Object -First 1
  if ($null -eq $v) { return $null }
  if ($null -ne $v.valueDecimal) { return $v.valueDecimal }
  if ($null -ne $v.valueCode) { return $v.valueCode }
  return $v.valueString
}

function Add-Found($found, $parts) {
  $code = ($parts | Where-Object { $_.name -eq 'code' } | Select-Object -First 1).valueCode
  $val = Get-PartValue $parts
  if ($code -and ($null -ne $val) -and -not $found.ContainsKey($code)) { $found[$code] = $val }
  foreach ($sub in ($parts | Where-Object { $_.name -eq 'subproperty' })) { Add-Found $found $sub.part }
}

function Get-Strength([string]$code) {
  $q = 'system=' + [uri]::EscapeDataString('http://snomed.info/sct') +
       '&version=' + [uri]::EscapeDataString($Edition) +
       '&code=' + $code
  foreach ($p in $AMT.Values) { $q += '&property=' + $p }
  $res = Invoke-RestMethod -Uri ($TxBase + '/CodeSystem/$lookup?' + $q) -Headers $headers
  $found = @{}
  foreach ($prop in ($res.parameter | Where-Object { $_.name -eq 'property' })) { Add-Found $found $prop.part }

  $conc = $null
  if ($found.ContainsKey($AMT.ConcValue) -and $found.ContainsKey($AMT.ConcUnit)) {
    $conc = [ordered]@{ value = [double]$found[$AMT.ConcValue]; snomedUnit = [string]$found[$AMT.ConcUnit] }
  }
  $total = $null
  if ($found.ContainsKey($AMT.TotalValue) -and $found.ContainsKey($AMT.TotalUnit)) {
    $total = [ordered]@{ value = [double]$found[$AMT.TotalValue]; snomedUnit = [string]$found[$AMT.TotalUnit] }
  }
  $boss = $null
  if ($found.ContainsKey($AMT.Boss)) { $boss = [string]$found[$AMT.Boss] }
  return [ordered]@{ boss = $boss; concentration = $conc; totalQuantity = $total }
}

$config = Get-Content -Raw -Path $guidelinePath | ConvertFrom-Json
$out = [ordered]@{
  _comment  = 'Generated by tools/build-medicines.ps1. Offline fallback used when Ontoserver is unreachable. Do not edit by hand.'
  generated = (Get-Date).ToString('yyyy-MM-dd')
  txBase    = $TxBase
  edition   = $Edition
  guidelines = [ordered]@{}
}

foreach ($g in $config.guidelines) {
  Write-Host ('Expanding ECL for ' + $g.id)
  $vsUrl = $Edition + '?fhir_vs=ecl/' + [uri]::EscapeDataString($g.drugEcl)
  $expandUri = $TxBase + '/ValueSet/$expand?count=200&url=' + [uri]::EscapeDataString($vsUrl)
  $vs = Invoke-RestMethod -Uri $expandUri -Headers $headers
  $items = @()
  foreach ($c in $vs.expansion.contains) {
    $s = Get-Strength $c.code
    $items += [ordered]@{
      code          = $c.code
      display       = $c.display
      boss          = $s.boss
      concentration = $s.concentration
      totalQuantity = $s.totalQuantity
    }
  }
  $items = @($items | Sort-Object { $_.display })
  Write-Host ('  ' + $items.Count + ' products')
  $out.guidelines[$g.id] = [ordered]@{ ecl = $g.drugEcl; items = $items }
}

$json = $out | ConvertTo-Json -Depth 8
[System.IO.File]::WriteAllText($outPath, $json, (New-Object System.Text.UTF8Encoding $false))
Write-Host ('Wrote ' + $outPath)
